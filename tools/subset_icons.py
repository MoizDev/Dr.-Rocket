"""Build the subsetted Material Symbols Rounded fonts used by the UI.

Usage: python tools/subset_icons.py <MaterialSymbolsRounded[...].ttf> <codepoints file>
Writes assets/fonts/MaterialSymbols{Outlined,Filled}.ttf and src/ui/icon_glyphs.rs.
"""
import sys, pathlib
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

