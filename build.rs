//! Embeds the Material Icon Theme SVGs referenced by `assets/icons/material-icon-theme.json`.

use std::fmt::Write;
use std::path::Path;

fn main() {
    let dir = Path::new("assets/icons/files");
    println!("cargo:rerun-if-changed=assets/icons");
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .expect("assets/icons/files")
        .flatten()
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".svg"))
        .collect();
    names.sort();
    let mut out = String::from("// @generated by build.rs\npub static FILE_ICON_SVGS: &[(&str, &[u8])] = &[\n");
    for n in &names {
        let abs = std::fs::canonicalize(dir.join(n)).unwrap();
        writeln!(out, "    ({:?}, include_bytes!({:?})),", n, abs.display().to_string()).unwrap();
    }
    out.push_str("];\n");
    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("file_icons.rs");
    std::fs::write(dest, out).unwrap();

    // Windows: the app icon in the .exe (Explorer, the taskbar, shortcuts).
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        println!("cargo:rerun-if-changed=assets/icon/icon.ico");
        let mut res = winresource::WindowsResource::new();
        res.set_icon("assets/icon/icon.ico");
        res.set("ProductName", "Dr. Rocket");
        res.set("FileDescription", "Dr. Rocket");
        if let Err(e) = res.compile() {
            println!("cargo:warning=could not embed the Windows icon: {e}");
        }
    }
}
